// Writes public/config.js (gitignored) with the Supabase URL + anon key for the landing page.
// Runs before every `npx wrangler deploy` (build.command in wrangler.jsonc).
// Both values are public by design (the anon key can only insert into `waitlist`), but they
// stay out of git like every other env value. Local preview (localhost) uses `supabase start`.
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const PROJECT_REF = 'qxulsfiminjhqenjogvr';
const repoRoot = new URL('../../', import.meta.url);
const run = (cmd) => execSync(cmd, { cwd: repoRoot, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });

const keys = JSON.parse(run(`npx supabase projects api-keys --project-ref ${PROJECT_REF} -o json`));
const hostedKey = keys.find((k) => k.name === 'anon')?.api_key;
if (!hostedKey) throw new Error('No hosted anon key: run `npx supabase login` first.');

let localKey = '';
try {
  localKey = run('npx supabase status -o env').match(/^ANON_KEY="(.+)"$/m)?.[1] ?? '';
} catch {
  // Local stack not running: local preview signups will show the "not set up" message.
}

const hosted = { supabaseUrl: `https://${PROJECT_REF}.supabase.co`, supabaseAnonKey: hostedKey };
const local = localKey ? { supabaseUrl: 'http://127.0.0.1:54321', supabaseAnonKey: localKey } : null;

writeFileSync(
  new URL('public/config.js', import.meta.url),
  `// Generated by gen-config.mjs - do not edit or commit.\n` +
    `window.LINKD_CONFIG = ['localhost', '127.0.0.1'].includes(location.hostname)\n` +
    `  ? ${JSON.stringify(local)}\n` +
    `  : ${JSON.stringify(hosted)};\n`,
);
console.log(`config.js written (local stack: ${local ? 'yes' : 'not running'})`);
